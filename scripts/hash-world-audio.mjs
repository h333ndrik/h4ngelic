import { createHash } from 'node:crypto';
import { readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Publishes the four world-sound files under content-hashed names and writes
 * the manifest the runtime imports. One copy per file: the published name is
 * the only name, so no stable URL survives. Idempotent; `--check` verifies
 * without touching the tree. */

export const HASH_LENGTH = 12;
export const EXTENSIONS = ['m4a', 'flac', 'wav'];
const EXPECTED = {
  loops: { '333': 'loop-333', '4': 'loop-4' },
  transitions: { 'x-333-4': 'x-333-4', 'x-4-333': 'x-4-333' },
};
const HASHED = /^(?<base>[a-z0-9][a-z0-9-]*)\.(?<hash>[0-9a-f]{8,64})\.(?<ext>m4a|flac|wav)$/i;
const STABLE = /^(?<base>[a-z0-9][a-z0-9-]*)\.(?<ext>m4a|flac|wav)$/i;

export function contentHash(bytes) {
  return createHash('sha256').update(bytes).digest('hex').slice(0, HASH_LENGTH);
}

export function hashedAudioName(base, ext, bytes) {
  return `${base}.${contentHash(bytes)}.${ext}`;
}

const byBase = (expected) => {
  const map = new Map();
  for (const group of Object.values(expected)) for (const base of Object.values(group)) map.set(base, []);
  return map;
};

/** Validates and normalises the audio directory, then returns the URL map. */
export async function hashWorldAudio({ root, check = false, log = () => {} } = {}) {
  const directory = join(root, 'public/assets/audio');
  const names = (await readdir(directory)).filter(name => !name.startsWith('.')).sort();
  const files = byBase(EXPECTED);

  for (const name of names) {
    const hashed = HASHED.exec(name);
    const stable = hashed ? null : STABLE.exec(name);
    if (!hashed && !stable) throw new Error(`Unexpected file in public/assets/audio: "${name}". Only the four world-sound assets may live here.`);
    const { base, ext } = hashed ? hashed.groups : stable.groups;
    if (!files.has(base)) throw new Error(`Unknown world-sound asset "${name}"; expected only ${[...files.keys()].join(', ')}.`);
    const bytes = await readFile(join(directory, name));
    if (hashed) {
      if (!contentHash(bytes).startsWith(hashed.groups.hash)) throw new Error(`Hash in "${name}" does not match its content.`);
      files.get(base).push({ base, ext, name, bytes, hash: hashed.groups.hash });
    } else {
      files.get(base).push({ base, ext, name, bytes, hash: contentHash(bytes), legacy: name });
    }
  }

  const manifest = { loops: {}, transitions: {} };
  const renames = [];
  for (const [group, ids] of Object.entries(EXPECTED)) {
    for (const [id, base] of Object.entries(ids)) {
      const candidates = files.get(base);
      if (!candidates.length) throw new Error(`Missing world-sound asset for "${base}".`);
      // One extension may not appear twice; a second hash means a stale copy.
      const seen = new Map();
      for (const file of candidates) {
        const previous = seen.get(file.ext);
        if (!previous) { seen.set(file.ext, file); continue; }
        if (previous.hash === file.hash) continue;
        throw new Error(`Two different ${file.ext} files for "${base}": ${previous.name} and ${file.name}. Remove the stale one.`);
      }
      const ordered = EXTENSIONS.map(ext => seen.get(ext)).filter(Boolean);
      for (const file of ordered) if (file.legacy) renames.push(file);
      manifest[group][id] = ordered.map(file => `/assets/audio/${file.legacy ? hashedAudioName(base, file.ext, file.bytes) : file.name}`);
    }
  }

  if (check) return { manifest, renames: renames.map(file => [file.legacy, hashedAudioName(file.base, file.ext, file.bytes)]), written: false };

  for (const file of renames) {
    const target = hashedAudioName(file.base, file.ext, file.bytes);
    await rename(join(directory, file.legacy), join(directory, target));
    log(`hashed ${file.legacy} -> ${target}`);
  }
  // Remove stale hashed variants of the four bases (older content).
  const permitted = new Set(Object.values(manifest).flatMap(group => Object.values(group).flat()).map(url => url.split('/').pop()));
  for (const name of names) {
    if (!HASHED.test(name) || permitted.has(name)) continue;
    await rm(join(directory, name));
    log(`removed stale ${name}`);
  }

  const source = `/** Generated by scripts/hash-world-audio.mjs. Do not edit by hand; run\n * \`npm run sounds:hash\` after replacing an audio file. */\nexport const worldSoundManifest = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`;
  await writeFile(join(root, 'src/audio/worldSoundManifest.js'), source);
  return { manifest, renames: renames.map(file => [file.legacy, hashedAudioName(file.base, file.ext, file.bytes)]), written: true };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const check = process.argv.includes('--check');
  const result = await hashWorldAudio({ root, check, log: message => console.log(message) });
  console.log(`${check ? 'checked' : 'hashed'}: ${Object.values(result.manifest).flatMap(group => Object.values(group)).flat().length} files`);
  for (const [key, urls] of Object.entries(result.manifest.loops)) console.log(`  loop ${key}: ${urls.join(', ')}`);
  for (const [key, urls] of Object.entries(result.manifest.transitions)) console.log(`  ${key}: ${urls.join(', ')}`);
}
